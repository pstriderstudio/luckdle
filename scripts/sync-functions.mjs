// Copies the shared game engine into supabase/functions/_shared/game-logic so
// Edge Functions can import it both when served locally (Docker) and when
// deployed. The copy is generated; edit packages/game-logic/src instead.
import { cpSync, rmSync, writeFileSync } from 'node:fs';

const target = new URL('../supabase/functions/_shared/game-logic/', import.meta.url);
rmSync(target, { recursive: true, force: true });
cpSync(new URL('../packages/game-logic/src/', import.meta.url), target, { recursive: true });
writeFileSync(new URL('README.md', target), 'Generated by `npm run functions:sync` from packages/game-logic/src. Do not edit.\n');
console.log('Synced packages/game-logic/src → supabase/functions/_shared/game-logic');
